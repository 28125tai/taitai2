# ==========================================
# โจทย์ข้อที่ 2: คำนวณระดับเกรด (0 - 4)
# Input: คะแนนสอบ (จำนวนเต็ม 0 - 100)
# เงื่อนไข:
#   - คะแนน >= 80 ได้เกรด 4
#   - คะแนน >= 70 ได้เกรด 3
#   - คะแนน >= 60 ได้เกรด 2
#   - คะแนน >= 50 ได้เกรด 1
#   - คะแนนน้อยกว่า 50 ได้เกรด 0
# Output: ตัวเลขเกรด (0, 1, 2, 3 หรือ 4)
# ==========================================

score = int(input())
if score >= 80:
    print("4")
elif score >= 70:
    print("3")
elif score >= 60:
    print("2")
elif score >= 50:
    print("1")
else: 
    print("0")
